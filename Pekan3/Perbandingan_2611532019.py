angka1_2019 = int(input("Input angka ke-1 : "))
angka2_2019 = int(input("Input angka ke-2 : "))

#Lebih besar dari 
hasil_2019 = angka1_2019 > angka2_2019
print("\nOperator Lebih Besar")
print("Hasil = ",hasil_2019)

#Lebih kecil dari 
hasil_2019 = angka1_2019 < angka2_2019
print("\nLebih kecil dari ")
print("Hasil = ",hasil_2019)

#Lebih besar dari atau sama dengan 
hasil_2019 = angka1_2019 >= angka2_2019
print("\nOperator Lebih besar dari atau sama dengan")
print("angka1 >= angka2 = ",hasil_2019)

#Lebih kecil dari atau sama dengan
hasil_2019 = angka1_2019 <= angka2_2019
print("\nOperator Lebih kecil dari atau sama dengan")
print("angka1 <= angka2 = ",hasil_2019)

#Sama dengan 
hasil_2019 = angka1_2019 == angka2_2019
print("\nOperator Sama dengan")
print("angka1 == angka2 = ",hasil_2019)

#Tidak sama dengan 
hasil_2019 = angka1_2019 != angka2_2019
print("\nOperator Tidak sama dengan")
print("Hasil = ",hasil_2019)


