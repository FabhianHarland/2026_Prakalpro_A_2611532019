# Program ini menggunakan konstanta untuk menghitun luas lingkaran
# nama variabel ditambah 4 digit nim terakhir contoh: jari_2019

phi = 3.14
jarijari_2019 = float(input("Masukkan jari-jari lingkaran : "))
keliling_2019 = float(2*phi*jarijari_2019)
luas_2019 = phi*jarijari_2019*jarijari_2019
print(f"jadi keliling dari lingkaran nya adalah : {keliling_2019}")
print(f"jadi luas dari lingkaran nya adalah : {luas_2019}")